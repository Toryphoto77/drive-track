-- DriveTrack 云端二期（腾讯 CloudBase PG 模式）建表 + RLS
--
-- 用法：控制台 → 数据库 → SQL 编辑器，把全文粘贴执行。
-- 全部语句可重复执行（IF NOT EXISTS / DROP POLICY IF EXISTS）。
-- 环境：上海地域、PG 模式（PostgreSQL）。
--
-- 关键点：App 默认是匿名登录，匿名 JWT 的 role 是 anon，但 sub
-- 是真实 user id。所以 GRANT 与策略必须同时覆盖 anon 与
-- authenticated 两个角色——只开 authenticated 会导致匿名用户
-- 上传/读不到自己的行程。

-- ============================================================
-- 1. trips 表（public schema；PostgREST 自动暴露成
--    https://<env>.api.tcloudbasegateway.com/v1/rdb/rest/trips）
-- ============================================================
CREATE TABLE IF NOT EXISTS public.trips (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner varchar(64) NOT NULL DEFAULT auth.uid(),
  mode varchar(16) NOT NULL DEFAULT 'car',
  started_at timestamptz NOT NULL,
  ended_at timestamptz NOT NULL,
  distance_m double precision NOT NULL DEFAULT 0,
  duration_s integer NOT NULL DEFAULT 0,
  source varchar(16) NOT NULL DEFAULT 'phone',
  max_speed_kmh double precision NOT NULL DEFAULT 0,
  score integer NOT NULL DEFAULT 0,
  storage_path text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS trips_owner_created_idx
  ON public.trips (owner, created_at DESC);

-- 行级安全：只放行本人（SELECT / INSERT / UPDATE / DELETE）。
ALTER TABLE public.trips ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.trips
  TO anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.trips_id_seq
  TO anon, authenticated;

DROP POLICY IF EXISTS trips_select_own ON public.trips;
CREATE POLICY trips_select_own ON public.trips
  FOR SELECT TO anon, authenticated
  USING (owner = auth.uid());

DROP POLICY IF EXISTS trips_insert_own ON public.trips;
CREATE POLICY trips_insert_own ON public.trips
  FOR INSERT TO anon, authenticated
  WITH CHECK (owner = auth.uid());

DROP POLICY IF EXISTS trips_update_own ON public.trips;
CREATE POLICY trips_update_own ON public.trips
  FOR UPDATE TO anon, authenticated
  USING (owner = auth.uid())
  WITH CHECK (owner = auth.uid());

DROP POLICY IF EXISTS trips_delete_own ON public.trips;
CREATE POLICY trips_delete_own ON public.trips
  FOR DELETE TO anon, authenticated
  USING (owner = auth.uid());

-- ============================================================
-- 2. 轨迹文件桶 storage.objects 策略
--    （桶本身在控制台新建，见 cloudbase/README.md；桶名 trip-files；
--    对象路径 <user id>/<trip id>.json，第一段目录即 owner）
-- ============================================================
ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS trip_files_insert_own ON storage.objects;
CREATE POLICY trip_files_insert_own ON storage.objects
  FOR INSERT TO anon, authenticated
  WITH CHECK (
    bucket_id = 'trip-files'
    AND (storage.foldername(name))[1] = auth.uid()
  );

-- upsert（同路径重传）要走 UPDATE，也要放行本人。
DROP POLICY IF EXISTS trip_files_update_own ON storage.objects;
CREATE POLICY trip_files_update_own ON storage.objects
  FOR UPDATE TO anon, authenticated
  USING (
    bucket_id = 'trip-files'
    AND (storage.foldername(name))[1] = auth.uid()
  )
  WITH CHECK (
    bucket_id = 'trip-files'
    AND (storage.foldername(name))[1] = auth.uid()
  );

DROP POLICY IF EXISTS trip_files_select_own ON storage.objects;
CREATE POLICY trip_files_select_own ON storage.objects
  FOR SELECT TO anon, authenticated
  USING (
    bucket_id = 'trip-files'
    AND (storage.foldername(name))[1] = auth.uid()
  );

DROP POLICY IF EXISTS trip_files_delete_own ON storage.objects;
CREATE POLICY trip_files_delete_own ON storage.objects
  FOR DELETE TO anon, authenticated
  USING (
    bucket_id = 'trip-files'
    AND (storage.foldername(name))[1] = auth.uid()
  );
