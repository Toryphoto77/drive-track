/// 仅含 M/L/C/Q/Z 的设计框路径，even-odd。
Path modeIconPath(String d) {
  final path = Path()..fillType = PathFillType.evenOdd;
  final tokens = RegExp(r'[MLCQZ]|-?\d*\.?\d+').allMatches(d).map((m) => m.group(0)!).toList();
  var i = 0;
  String? cmd;
  double read() => double.parse(tokens[i++]);
  while (i < tokens.length) {
    final t = tokens[i];
    if (t == 'M' || t == 'L' || t == 'C' || t == 'Q' || t == 'Z') {
      cmd = t;
      i++;
      if (cmd == 'Z') path.close();
      continue;
    }
    if (cmd == 'M' || cmd == 'L') {
      final x = double.parse(t);
      i++;
      final y = read();
      if (cmd == 'M') {
        path.moveTo(x, y);
        cmd = 'L';
      } else {
        path.lineTo(x, y);
      }
    } else if (cmd == 'C') {
      final x1 = double.parse(t);
      i++;
      final y1 = read();
      final x2 = read();
      final y2 = read();
      final x = read();
      final y = read();
      path.cubicTo(x1, y1, x2, y2, x, y);
    } else if (cmd == 'Q') {
      final x1 = double.parse(t);
      i++;
      final y1 = read();
      final x = read();
      final y = read();
      path.quadraticBezierTo(x1, y1, x, y);
    } else {
      i++;
    }
  }
  return path;
}

